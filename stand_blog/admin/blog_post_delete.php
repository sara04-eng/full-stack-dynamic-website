<?php

include '../config.php';

/*
|--------------------------------------------------------------------------
| Get Blog Post ID
|--------------------------------------------------------------------------
*/

$id = isset($_GET['id']) && is_numeric($_GET['id'])
    ? (int) $_GET['id']
    : 0;


/*
|--------------------------------------------------------------------------
| Check ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    header("Location: posts.php");

    exit;
}


/*
|--------------------------------------------------------------------------
| Check if Blog Post Exists
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM blogs
    WHERE id = ?
");

$stmt->execute([$id]);

$post = $stmt->fetch(PDO::FETCH_ASSOC);


/*
|--------------------------------------------------------------------------
| Blog Post Not Found
|--------------------------------------------------------------------------
*/

if (!$post) {

    header("Location: posts.php?error=notfound");

    exit;
}


/*
|--------------------------------------------------------------------------
| Delete Blog Post
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    DELETE FROM blogs
    WHERE id = ?
");

$stmt->execute([$id]);


/*
|--------------------------------------------------------------------------
| Redirect Back to Posts
|--------------------------------------------------------------------------
*/

header("Location: posts.php?deleted=1");

exit;

?>