
<?php

include '../config.php';

/*
|--------------------------------------------------------------------------
| Get Comment ID
|--------------------------------------------------------------------------
*/

$id = isset($_GET['id']) && is_numeric($_GET['id'])
    ? (int) $_GET['id']
    : 0;


/*
|--------------------------------------------------------------------------
| Check ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    header("Location: comments.php");

    exit;
}


/*
|--------------------------------------------------------------------------
| Check if Comment Exists
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM comments
    WHERE id = ?
");

$stmt->execute([$id]);

$comment = $stmt->fetch(PDO::FETCH_ASSOC);


/*
|--------------------------------------------------------------------------
| Comment Not Found
|--------------------------------------------------------------------------
*/

if (!$comment) {

    header("Location: comments.php?error=notfound");

    exit;
}


/*
|--------------------------------------------------------------------------
| Delete Comment
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    DELETE FROM comments
    WHERE id = ?
");

$stmt->execute([$id]);


/*
|--------------------------------------------------------------------------
| Redirect Back to Comments
|--------------------------------------------------------------------------
*/

header("Location: comments.php?deleted=1");

exit;

?>

