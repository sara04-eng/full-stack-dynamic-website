<?php

include '../config.php';

/*
|--------------------------------------------------------------------------
| Get Contact ID
|--------------------------------------------------------------------------
*/

$id = isset($_GET['id']) && is_numeric($_GET['id'])
    ? (int) $_GET['id']
    : 0;


/*
|--------------------------------------------------------------------------
| Check ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    header("Location: contact_info.php?error=invalid");

    exit;
}


/*
|--------------------------------------------------------------------------
| Check if Contact Information Exists
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM contact_info
    WHERE id = ?
");

$stmt->execute([$id]);

$contact = $stmt->fetch(PDO::FETCH_ASSOC);


/*
|--------------------------------------------------------------------------
| Contact Information Not Found
|--------------------------------------------------------------------------
*/

if (!$contact) {

    header("Location: contact_info.php?error=notfound");

    exit;
}


/*
|--------------------------------------------------------------------------
| Delete Contact Information
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    DELETE FROM contact_info
    WHERE id = ?
");

$stmt->execute([$id]);


/*
|--------------------------------------------------------------------------
| Redirect Back
|--------------------------------------------------------------------------
*/

header("Location: contact_info.php?deleted=1");

exit;

?>