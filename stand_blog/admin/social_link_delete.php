<?php

include '../config.php';

/*
|--------------------------------------------------------------------------
| Get Social Link ID
|--------------------------------------------------------------------------
*/

$id = isset($_GET['id']) && is_numeric($_GET['id'])
    ? (int) $_GET['id']
    : 0;


/*
|--------------------------------------------------------------------------
| Check ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    header("Location: social_links.php");

    exit;
}


/*
|--------------------------------------------------------------------------
| Check if Social Link Exists
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM social_links
    WHERE id = ?
");

$stmt->execute([$id]);

$link = $stmt->fetch(PDO::FETCH_ASSOC);


/*
|--------------------------------------------------------------------------
| If Not Found
|--------------------------------------------------------------------------
*/

if (!$link) {

    header("Location: social_links.php?error=notfound");

    exit;
}


/*
|--------------------------------------------------------------------------
| Delete Social Link
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    DELETE FROM social_links
    WHERE id = ?
");

$stmt->execute([$id]);


/*
|--------------------------------------------------------------------------
| Redirect Back
|--------------------------------------------------------------------------
*/

header("Location: social_links.php?deleted=1");

exit;

?>